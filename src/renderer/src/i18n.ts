export const LANGS = { en, uz }
export type Lang = keyof typeof LANGS

const KEY = 'ai-office.lang'
const listeners = new Set<() => void>()

function initial(): Lang {
  try {
    const saved = localStorage.getItem(KEY)
    if (saved === 'en' || saved === 'uz') return saved
  } catch {
    // storage unavailable: fall back to the system language
  }
  return navigator.language.toLowerCase().startsWith('uz') ? 'uz' : 'en'
}

let current: Lang = initial()
// index.html ships lang="uz"; screen readers need the language actually shown.
if (typeof document !== 'undefined') document.documentElement.lang = current

export function setLang(l: Lang) {
  current = l
  try {
    localStorage.setItem(KEY, l)
  } catch {
    // not persisted; still applies for this session
  }
  document.documentElement.lang = l
  listeners.forEach((f) => f())
}

export const getLang = () => current

export function useT(): Dict {
  const lang = useSyncExternalStore(
    (f) => {
      listeners.add(f)
      return () => listeners.delete(f)
    },
    () => current
  )
  return LANGS[lang]
}

/** Main-process errors arrive as `CODE` or `CODE|param`; anything else is shown as-is. */
export function errText(e: unknown, t: Dict = LANGS[current]): string {
  const raw = (e instanceof Error ? e.message : String(e)).replace(/^Error invoking remote method '[^']+': (Error: )?/, '')
  const m = /^(E_[A-Z_]+)(?:\|(.*))?$/.exec(raw)
  const msg = m && t.errors[m[1]]
  if (!msg) return raw
  return typeof msg === 'function' ? msg(m[2] ?? '') : msg
}
